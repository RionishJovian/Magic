#!/usr/bin/env node
/**
 * Rebuild the hub's URI and WebFig-cookie peer maps from peers.json.
 * Run after peer create/remove, or from cron.
 */
import fs from "node:fs";
import { execFileSync } from "node:child_process";

const PEERS_PATH = process.env.MM_HUB_PEERS_PATH || "/var/lib/mikromagic-hub/peers.json";
const REST_MAP_PATH = process.env.MM_HUB_PEER_REST_MAP || "/etc/nginx/mikromagic-peer-rest.map";
const ID_MAP_PATH = process.env.MM_HUB_PEER_ID_MAP || "/etc/nginx/mikromagic-peer-id.map";
const RELOAD = process.env.MM_HUB_NGINX_RELOAD !== "0";

function loadPeers() {
  try {
    const parsed = JSON.parse(fs.readFileSync(PEERS_PATH, "utf8"));
    return Array.isArray(parsed) ? parsed : Array.isArray(parsed.peers) ? parsed.peers : [];
  } catch {
    return [];
  }
}

function activePeerKeys(peers) {
  const keys = [];
  const seen = new Set();
  for (const peer of peers) {
    if (peer.state === "removed" || peer.state === "disabled") continue;
    const peerId = String(peer.peerId || "").trim();
    const tunnelIp = String(peer.tunnelAddress || "")
      .split("/")[0]
      .trim();
    if (!peerId || !tunnelIp) continue;
    const aliases = new Set([peerId]);
    if (peerId.startsWith("peer_")) aliases.add(peerId.slice("peer_".length));
    for (const key of aliases) {
      if (!key || seen.has(key)) continue;
      seen.add(key);
      keys.push([key, tunnelIp]);
    }
  }
  return keys;
}

export function buildMapFiles(peers) {
  const keys = activePeerKeys(peers);
  return {
    rest: [
      "# Generated by mikromagic-sync-peer-rest-map — do not edit — URI regex map",
      ...keys.flatMap(([key, ip]) => [
        `~^/peers/${key}/rest  ${ip};`,
        `~^/peers/${key}/open-webfig/?$  ${ip};`,
      ]),
    ],
    ids: [
      "# Generated by mikromagic-sync-peer-rest-map — do not edit — peer id map",
      ...keys.map(([key, ip]) => `${key}  ${ip};`),
    ],
  };
}

function main() {
  const maps = buildMapFiles(loadPeers());
  fs.writeFileSync(REST_MAP_PATH, `${maps.rest.join("\n")}\n`, { mode: 0o644 });
  fs.writeFileSync(ID_MAP_PATH, `${maps.ids.join("\n")}\n`, { mode: 0o644 });
  console.log(`wrote ${maps.rest.length - 1} URI and ${maps.ids.length - 1} peer-id entries`);
  if (RELOAD) {
    execFileSync("nginx", ["-t"], { stdio: "inherit" });
    execFileSync("systemctl", ["reload", "nginx"], { stdio: "inherit" });
  }
}

if (
  import.meta.url === `file://${process.argv[1]}` ||
  process.argv[1]?.endsWith("sync-peer-rest-map.mjs")
)
  main();
